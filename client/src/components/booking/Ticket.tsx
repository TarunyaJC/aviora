import { useEffect, useState } from 'react';
import { Download, Printer } from 'lucide-react';
import { QRCodeSVG } from 'qrcode.react';
import { useFlight, usePayment } from '@/hooks/useApi';
import { formatINR, formatTime, formatDate, formatDuration } from '@/utils/format';
import { BOARDING_GROUP_BY_CABIN, PAYMENT_METHOD_LABEL } from '@/constants/app';
import type { Booking } from '@/types/domain';

interface TicketProps {
  booking: Booking;
}

/** One boarding pass per passenger, with payment + baggage info on the first stub. */
export function Ticket({ booking }: TicketProps) {
  const { data: flight } = useFlight(booking.flightId);
  const { data: payment } = usePayment(booking.paymentId);
  const [qrValue, setQrValue] = useState('');

  const firstPassenger = booking.passengers[0];

  useEffect(() => {
    if (!flight || !firstPassenger) return;
    setQrValue(
      JSON.stringify({
        ref: booking.reference,
        pax: `${firstPassenger.firstName} ${firstPassenger.lastName}`,
        seat: firstPassenger.seatId,
        flight: flight.flightNumber,
        from: flight.from,
        to: flight.to,
        date: flight.departure.slice(0, 10),
        demo: true,
      }),
    );
  }, [booking.reference, flight, firstPassenger]);

  if (!flight) return null;

  const group = BOARDING_GROUP_BY_CABIN[booking.cabin];
  // Captured so the download handler keeps a non-optional flight reference.
  const confirmedFlight = flight;
  const methodLabel = payment ? PAYMENT_METHOD_LABEL[payment.method] : 'Demo payment';

  function paymentSummaryLine(): string {
    if (!payment) return `${formatINR(booking.totalAmount)} (demo payment)`;
    const detail = payment.methodDetail;
    const bits: string[] = [methodLabel];
    if (detail.last4) bits.push(`•••• ${detail.last4}`);
    if (detail.upiId) bits.push(detail.upiId);
    if (detail.bank) bits.push(detail.bank);
    if (detail.provider) bits.push(detail.provider);
    if (detail.tenureMonths) bits.push(`${detail.tenureMonths}-month no-cost EMI`);
    return `${formatINR(booking.totalAmount)} via ${bits.join(' ')} · TXN ${payment.transactionRef}`;
  }

  function downloadTicket(): void {
    const ticketText = [
      '══════════════════════════════════════════════',
      '  AVIORA — ELECTRONIC TICKET / BOARDING PASS',
      '══════════════════════════════════════════════',
      `Booking Reference : ${booking.reference}`,
      `Flight            : ${confirmedFlight.flightNumber} (${confirmedFlight.airline.name})`,
      `Aircraft          : ${confirmedFlight.aircraft.model}`,
      `Route             : ${confirmedFlight.from} → ${confirmedFlight.to}`,
      `Date              : ${formatDate(confirmedFlight.departure)}`,
      `Departure         : ${formatTime(confirmedFlight.departure)}   Terminal ${confirmedFlight.terminal}`,
      `Gate              : ${confirmedFlight.gate ?? 'TBD'}`,
      `Arrival           : ${formatTime(confirmedFlight.arrival)}`,
      `Duration          : ${formatDuration(confirmedFlight.durationMinutes)}`,
      `Cabin             : ${booking.cabin} · Boarding group ${group}`,
      `Baggage allowance : ${booking.cabin === 'Business' ? 35 : booking.cabin === 'Premium Economy' ? 25 : 15} kg checked`,
      '',
      ...booking.passengers.map(
        (p) => `Passenger         : ${p.firstName} ${p.lastName}   Seat ${p.seatId}   ${p.gender}, ${p.nationality}`,
      ),
      '',
      `Payment           : ${paymentSummaryLine()}`,
      `Status            : ${booking.status}`,
      '',
      'Demo e-ticket generated by AVIORA. Not valid for actual travel.',
      '══════════════════════════════════════════════',
    ].join('\n');

    const blob = new Blob([ticketText], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = `AVIORA-eTicket-${booking.reference}.txt`;
    anchor.click();
    URL.revokeObjectURL(url);
  }

  const label = 'text-[9px] uppercase tracking-[0.22em] text-silver';
  const value = 'font-display text-sm font-semibold text-frost';

  return (
    <div className="space-y-6">
      {booking.passengers.map((passenger, pIndex) => (
        <article
          key={passenger.id}
          className="ticket-shell overflow-hidden rounded-3xl border border-white/10 bg-gradient-to-br from-graphite via-midnight to-obsidian"
        >
          <div className="grid sm:grid-cols-[1fr_150px]">
            {/* Main stub */}
            <div className="p-6 sm:p-7">
              <div className="flex items-center justify-between">
                <p className="font-display text-sm font-bold tracking-[0.3em] text-champagne">AVIORA</p>
                <p className={label}>E-Ticket · Boarding Pass · DEMO</p>
              </div>

              <div className="mt-5 grid grid-cols-2 gap-4 sm:grid-cols-4">
                <div>
                  <p className={label}>Passenger</p>
                  <p className={`${value} mt-0.5`}>{passenger.firstName} {passenger.lastName}</p>
                </div>
                <div>
                  <p className={label}>Reference</p>
                  <p className={`${value} mt-0.5 text-champagne`}>{booking.reference}</p>
                </div>
                <div>
                  <p className={label}>Flight</p>
                  <p className={`${value} mt-0.5`}>{flight.flightNumber}</p>
                </div>
                <div>
                  <p className={label}>Date</p>
                  <p className={`${value} mt-0.5`}>{formatDate(flight.departure)}</p>
                </div>
              </div>

              <div className="mt-5 grid grid-cols-2 gap-4 sm:grid-cols-5">
                <div>
                  <p className={label}>From</p>
                  <p className="font-display text-2xl font-bold text-frost">{flight.from}</p>
                  <p className="text-xs text-silver">{formatTime(flight.departure)}</p>
                </div>
                <div className="flex items-end pb-1">
                  <span className="h-px w-full bg-gradient-to-r from-silver/40 to-champagne/60" aria-hidden />
                </div>
                <div>
                  <p className={label}>To</p>
                  <p className="font-display text-2xl font-bold text-frost">{flight.to}</p>
                  <p className="text-xs text-silver">{formatTime(flight.arrival)}</p>
                </div>
                <div>
                  <p className={label}>Seat</p>
                  <p className="font-display text-2xl font-bold text-champagne">{passenger.seatId}</p>
                  <p className="text-xs text-silver">{booking.cabin}</p>
                </div>
                <div>
                  <p className={label}>Group</p>
                  <p className="font-display text-2xl font-bold text-frost">{group + pIndex}</p>
                  <p className="text-xs text-silver">Gate {flight.gate ?? 'TBD'} · T{flight.terminal}</p>
                </div>
              </div>

              {pIndex === 0 ? (
                <div className="mt-6 grid gap-3 border-t border-dashed border-white/15 pt-4 text-xs sm:grid-cols-2">
                  <div>
                    <p className={label}>Payment</p>
                    <p className="mt-0.5 text-silver">
                      {payment ? paymentSummaryLine() : `${formatINR(booking.totalAmount)} (demo payment)`}
                    </p>
                  </div>
                  <div>
                    <p className={label}>Baggage · Cabin {booking.cabin}</p>
                    <p className="mt-0.5 text-silver">
                      {booking.cabin === 'Business' ? 35 : booking.cabin === 'Premium Economy' ? 25 : 15} kg checked ·{' '}
                      {booking.passengers.length} passenger{booking.passengers.length > 1 ? 's' : ''}
                    </p>
                  </div>
                </div>
              ) : null}
            </div>

            {/* QR stub */}
            <div className="relative border-t border-dashed border-white/15 bg-obsidian/60 p-5 sm:border-l sm:border-t-0 sm:border-dashed">
              <div className="rounded-xl bg-white p-2.5">
                {qrValue ? (
                  <QRCodeSVG
                    value={qrValue}
                    size={118}
                    level="M"
                    aria-label={`QR code for ${passenger.firstName} ${passenger.lastName}, seat ${passenger.seatId}`}
                  />
                ) : (
                  <div className="size-[118px] animate-pulse rounded bg-silver/20" aria-hidden />
                )}
              </div>
              <p className="mt-2 text-center font-display text-xs tracking-[0.25em] text-frost">{booking.reference}</p>
              <p className="text-center text-[9px] text-silver/70">
                {passenger.seatId} · scan at gate (demo)
              </p>
            </div>
          </div>
        </article>
      ))}

      <div className="flex flex-wrap gap-3 no-print">
        <button
          type="button"
          onClick={downloadTicket}
          className="inline-flex items-center gap-2 rounded-full bg-champagne px-5 py-2.5 text-xs font-semibold text-obsidian transition-colors hover:bg-champagne-soft cursor-pointer"
        >
          <Download className="size-3.5" aria-hidden /> Download e-ticket
        </button>
        <button
          type="button"
          onClick={() => window.print()}
          className="inline-flex items-center gap-2 rounded-full border border-silver/30 px-5 py-2.5 text-xs font-semibold text-frost transition-colors hover:border-champagne/60 hover:bg-champagne/5 cursor-pointer"
        >
          <Printer className="size-3.5" aria-hidden /> Print e-ticket
        </button>
      </div>
    </div>
  );
}
